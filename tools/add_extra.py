"""Register a repository-bundled game in extras/manifest.json.

Run from the project root:
    python tools/add_extra.py
"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXTRAS = ROOT / "extras"
JSON_MANIFEST = EXTRAS / "manifest.json"
JS_MANIFEST = EXTRAS / "manifest.js"


def relative_file(folder: Path, value: str, label: str, required: bool) -> str | None:
    value = value.strip()
    if not value:
        if required:
            raise ValueError(f"{label} is required.")
        return None
    candidate = (folder / value).resolve()
    if folder not in candidate.parents and candidate != folder:
        raise ValueError(f"{label} must stay inside the selected game folder.")
    if not candidate.is_file():
        raise ValueError(f"{label} was not found: {candidate.relative_to(ROOT)}")
    return candidate.relative_to(folder).as_posix()


def main() -> None:
    EXTRAS.mkdir(exist_ok=True)
    print("Add a bundled game to Neon Snake\n")

    name = input("Game name: ").strip()
    if not name:
        raise ValueError("Game name is required.")

    folder_name = input("Folder inside extras/: ").strip().replace("\\", "/")
    if not folder_name or folder_name.startswith("/") or ".." in Path(folder_name).parts:
        raise ValueError("Enter a folder path inside extras/, for example my-game.")
    folder = (EXTRAS / folder_name).resolve()
    if not folder.is_dir() or EXTRAS not in folder.parents:
        raise ValueError(f"Folder not found inside extras/: {folder_name}")

    html_files = sorted(folder.rglob("*.html")) + sorted(folder.rglob("*.htm"))
    default_entry = "index.html" if (folder / "index.html").is_file() else (
        html_files[0].relative_to(folder).as_posix() if html_files else "index.html"
    )
    entry_input = input(f"Entry HTML [{default_entry}]: ").strip() or default_entry
    entry = relative_file(folder, entry_input, "Entry HTML", required=True)

    thumbnail_input = input("Thumbnail path inside the game folder (optional): ").strip()
    thumbnail = relative_file(folder, thumbnail_input, "Thumbnail", required=False)

    entries = []
    if JSON_MANIFEST.is_file():
        entries = json.loads(JSON_MANIFEST.read_text(encoding="utf-8"))

    manifest_entry = {"name": name, "entry": f"{folder_name}/{entry}"}
    if thumbnail:
        manifest_entry["thumbnail"] = f"{folder_name}/{thumbnail}"

    entries = [item for item in entries if item.get("entry") != manifest_entry["entry"]]
    entries.append(manifest_entry)
    entries.sort(key=lambda item: item["name"].lower())

    JSON_MANIFEST.write_text(json.dumps(entries, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    js_entries = json.dumps(entries, indent=2, ensure_ascii=False)
    js = (
        "// This file is generated by tools/add_extra.py.\n"
        f"window.NEON_SNAKE_EXTRAS = {js_entries}.map(game => ({{\n"
        "  ...game,\n"
        "  url: `extras/${game.entry}`,\n"
        "  thumbnail: game.thumbnail ? `extras/${game.thumbnail}` : ''\n"
        "}));\n"
    )
    JS_MANIFEST.write_text(js, encoding="utf-8")
    print(f"\nAdded '{name}'. Reload index.html to see it in Extras.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, json.JSONDecodeError) as error:
        raise SystemExit(f"Error: {error}")
